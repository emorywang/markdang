export type MessageKey = keyof typeof messages
export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string

export function normalizeLanguage(value: unknown): Language {
  if (typeof value !== 'string') return 'auto'
  const tag = value.trim().replaceAll('_', '-').toLowerCase()
  if (tag === 'zh' || tag.startsWith('zh-')) return 'zh-CN'
  if (tag === 'en' || tag.startsWith('en-')) return 'en'
  return 'auto'
}

export function resolveLocale(language: Language = 'auto', browserLanguage?: string): Locale {
  if (language !== 'auto') return language
  const tag = browserLanguage ?? globalThis.chrome?.i18n?.getUILanguage?.() ?? globalThis.navigator?.language ?? 'en'
  return normalizeLanguage(tag) === 'zh-CN' ? 'zh-CN' : 'en'
}

export function createTranslator(language: Language = 'auto', browserLanguage?: string): Translator {
  const index = resolveLocale(language, browserLanguage) === 'zh-CN' ? 0 : 1
  return (key, values = {}) => messages[key][index].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match))
}
